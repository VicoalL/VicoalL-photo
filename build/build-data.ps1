param(
  [Parameter(Mandatory=$true)][string]$Manifest,
  [string]$PicksJson = "",
  [string]$ExcludeList = "",
  [string]$StarsList = "",
  [Parameter(Mandatory=$true)][string]$Out
)
$ErrorActionPreference = 'Stop'
Add-Type -AssemblyName System.Drawing

$items = [System.IO.File]::ReadAllText($Manifest, [System.Text.Encoding]::UTF8) | ConvertFrom-Json

function Read-List([string]$path) {
  $h = @{}
  if ($path -and (Test-Path -LiteralPath $path)) {
    foreach ($line in [System.IO.File]::ReadAllLines($path, [System.Text.Encoding]::UTF8)) {
      $s = $line.Trim()
      if ($s -and -not $s.StartsWith("#")) { $h[$s] = $true }
    }
  }
  return $h
}
$exclude = Read-List $ExcludeList
$stars = Read-List $StarsList

$picks = @{}
if ($PicksJson -and (Test-Path -LiteralPath $PicksJson)) {
  $pj = [System.IO.File]::ReadAllText($PicksJson, [System.Text.Encoding]::UTF8) | ConvertFrom-Json
  foreach ($p in $pj.PSObject.Properties) { $picks[$p.Name] = @($p.Value) }
}

$ids = @{
  0x010F='Make'; 0x0110='Model'; 0x829A='Exp'; 0x829D='FNum'; 0x8827='ISO';
  0x920A='Focal'; 0x9003='Date'; 0xA434='Lens'
}
function Read-Exif([string]$path) {
  $o = @{ cam=''; lens=''; fnum=''; exp=''; iso=0; focal=0; date=''; w=0; h=0 }
  try {
    $img = [System.Drawing.Image]::FromFile($path)
    $o.w = $img.Width; $o.h = $img.Height
    foreach ($pi in $img.PropertyItems) {
      $k = $ids[$pi.Id]
      if (-not $k) { continue }
      switch ($k) {
        'Model' { $o.cam  = ([System.Text.Encoding]::ASCII.GetString($pi.Value)).Trim([char]0) }
        'Lens'  { $o.lens = ([System.Text.Encoding]::ASCII.GetString($pi.Value)).Trim([char]0) }
        'Date'  { $o.date = ([System.Text.Encoding]::ASCII.GetString($pi.Value)).Trim([char]0) }
        'ISO'   { $o.iso  = [System.BitConverter]::ToUInt16($pi.Value, 0) }
        'Focal' { $o.focal = [int][Math]::Round([System.BitConverter]::ToUInt32($pi.Value, 0) / [double][System.BitConverter]::ToUInt32($pi.Value, 4), 0) }
        'FNum'  { $o.fnum = [Math]::Round([System.BitConverter]::ToUInt32($pi.Value, 0) / [double][System.BitConverter]::ToUInt32($pi.Value, 4), 1) }
        'Exp'   {
          $num = [System.BitConverter]::ToUInt32($pi.Value, 0)
          $den = [System.BitConverter]::ToUInt32($pi.Value, 4)
          if ($num -gt 0 -and $den -gt 0) { if ($num -eq 1) { $o.exp = "1/" + $den } else { $o.exp = ([Math]::Round($num / $den, 2)).ToString() } }
        }
      }
    }
    $img.Dispose()
  } catch {}
  return $o
}

$bySlug = @{}
$seenHash = @{}
$skipped = 0
$baseDir = Split-Path $Manifest -Parent

foreach ($it in $items) {
  $leaf = Split-Path $it.src -Leaf
  $slug = $it.slug
  if ($it.out -match '^[0-9a-f]{8}-' -and $it.out -notmatch '^5794edcf') { $slug = 'composites' }
  if ($exclude.ContainsKey($it.out)) { $skipped++; continue }
  if (-not $bySlug.ContainsKey($slug)) { $bySlug[$slug] = @() }

  $webPath = Join-Path $baseDir ("web\" + $slug + "\" + $it.out)
  $h = ''
  try { $h = (Get-FileHash -LiteralPath $webPath -Algorithm MD5).Hash } catch {}
  if ($h -and $seenHash.ContainsKey($h)) { continue }
  if ($h) { $seenHash[$h] = $true }

  $exif = Read-Exif $it.src
  $isPick = $false
  if ($picks.ContainsKey($slug)) { $isPick = ($picks[$slug] -contains $leaf) }
  $date = ''
  if ($exif.date -match '^(\d{4}):(\d{2}):(\d{2})') { $date = $matches[1] + '-' + $matches[2] + '-' + $matches[3] }
  $rank = 1
  if ($stars.ContainsKey($leaf)) { $rank = 0 }

  $bySlug[$slug] += [pscustomobject]@{
    f = $it.out; w = $exif.w; h = $exif.h; pick = $isPick; rank = $rank
    cam = $exif.cam; lens = $exif.lens; fnum = $exif.fnum; exp = $exif.exp
    iso = $exif.iso; focal = $exif.focal; date = $date
  }
}

$meta = [ordered]@{
  field  = @{ title='Fieldwork';  cn='田野'; surface='green';  note='三下乡 · 支教十天' }
  campus = @{ title='Campus';     cn='校园'; surface='blue';   note='高中三年 · 国旗队' }
  uni    = @{ title='University'; cn='大学'; surface='pink';   note='活动 · 舞台 · 人物' }
  scene  = @{ title='Landscape';  cn='风景'; surface='purple'; note='星空 · 山野 · 海边' }
  sport  = @{ title='Sport';      cn='赛场'; surface='orange'; note='高中运动会' }
  cos    = @{ title='COS';        cn='角色'; surface='slate';  note='角色扮演' }
  composites = @{ title='Composites'; cn='合成'; surface='slate'; note='照片 + 二次创作' }
}

$order = @('field','campus','uni','scene','sport')

$sb = New-Object System.Text.StringBuilder
[void]$sb.AppendLine('/* generated by build\build-data.ps1 - do not edit by hand */')
[void]$sb.AppendLine('window.SITE = {')
[void]$sb.AppendLine('  order: [' + (($order | ForEach-Object { '"' + $_ + '"' }) -join ', ') + '],')
[void]$sb.AppendLine('  chapters: {')

foreach ($slug in $meta.Keys) {
  if (-not $bySlug.ContainsKey($slug)) { continue }
  $list = $bySlug[$slug] | Sort-Object rank, date, f
  $m = $meta[$slug]
  $dates = @($list | Where-Object { $_.date } | ForEach-Object { $_.date } | Sort-Object)
  $range = ''
  if ($dates.Count -gt 0) {
    $a = $dates[0].Substring(0,7); $b = $dates[-1].Substring(0,7)
    if ($a -eq $b) { $range = $a } else { $range = "$a — $b" }
  }
  [void]$sb.AppendLine('    ' + $slug + ': { title: "' + $m.title + '", cn: "' + $m.cn + '", surface: "' + $m.surface +
    '", note: "' + $m.note + '", range: "' + $range + '", total: ' + $list.Count + ', photos: [')
  $rows = @()
  foreach ($x in $list) {
    $rows += ('      { f: "' + $x.f + '", w: ' + $x.w + ', h: ' + $x.h + ', pick: ' + $x.pick.ToString().ToLower() +
              ', rank: ' + $x.rank +
              ', cam: "' + $x.cam + '", lens: "' + $x.lens + '", fnum: "' + $x.fnum + '", exp: "' + $x.exp +
              '", iso: ' + $x.iso + ', focal: ' + $x.focal + ', date: "' + $x.date + '" }')
  }
  [void]$sb.AppendLine(($rows -join ",`n"))
  [void]$sb.AppendLine('    ] },')
}
[void]$sb.AppendLine('  }')
[void]$sb.AppendLine('};')

[System.IO.File]::WriteAllText($Out, $sb.ToString(), (New-Object System.Text.UTF8Encoding($false)))

$sum = 0
foreach ($slug in $order) {
  if (-not $bySlug.ContainsKey($slug)) { continue }
  $c = $bySlug[$slug].Count
  $p = @($bySlug[$slug] | Where-Object { $_.pick }).Count
  $sum += $c
  Write-Output ("{0,-7} {1,4} photos  picks={2}" -f $slug, $c, $p)
}
if ($bySlug.ContainsKey('composites')) { Write-Output ("{0,-7} {1,4} photos" -f 'composites', $bySlug['composites'].Count) }
Write-Output ("TOTAL " + $sum + "  excluded=" + $skipped + " -> " + $Out)
